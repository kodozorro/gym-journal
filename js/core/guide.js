/** Какое упражнение делают на тренажёре: единственное или выбранное по названию. */
const ON_MACHINE = {
  'seated-leg-press': () => 'seated-leg-press',
  'leg-press': () => 'leg-press',
  'hack-press': () => 'hack-press',
  'leg-curl': () => 'leg-curl',
  'chest-press': () => 'chest-press',
  'shoulder-press': () => 'shoulder-press',
  'lateral-raise': () => 'lateral-raise',
  treadmill: () => 'treadmill',
  'low-pulley': (exercise) => (/широк/.test(exercise) ? 'row-wide' : 'row-narrow'),
  'pec-deck': (exercise) => (/обратн/.test(exercise) ? 'reverse-fly' : /сведени/.test(exercise) ? 'pec-fly' : ''),
};

/** Если тренажёр в таблице не указан, упражнение узнаётся по своему названию. */
const BY_NAME = [
  [/^жим ногами сидя/, 'seated-leg-press'],
  [/^жим ногами/, 'leg-press'],
  [/гакк/, 'hack-press'],
  [/сгибание ног/, 'leg-curl'],
  [/жим от груди/, 'chest-press'],
  [/жим вверх/, 'shoulder-press'],
  [/тяга сидя.*широк/, 'row-wide'],
  [/тяга сидя/, 'row-narrow'],
  [/обратн.*разведени/, 'reverse-fly'],
  [/сведение рук/, 'pec-fly'],
  [/разведение рук в стороны/, 'lateral-raise'],
  [/^ходьба/, 'treadmill'],
];

export const STRENGTH_RULE = 'Вес берите такой, чтобы в конце подхода оставалось 2–3 повтора в запасе. Амплитуда полная, но без боли.';
// «яркая», а не «тёмная»: в тёмной теме фигура светлая
export const LEGEND = 'Яркая и бледная фигуры — крайние положения, стрелка — рабочее усилие.';

const clean = (text) => String(text || '').toLowerCase().replace(/ё/g, 'е').replace(/\s+/g, ' ').trim();

/** Тип тренажёра по названию из таблицы или null. */
export function machineOf(name) {
  const text = clean(name);
  return (text && MACHINES.find((item) => item.test.test(text))) || null;
}

/**
 * Что показать по кнопке «i».
 * @param {{exercise?: string, machine?: string}} row строка журнала
 * @returns {{
 *   machine: string, photo: {src: string, width: number, height: number}|null, look: string,
 *   art: string, view: string, legend: string, muscles: string, steps: string[], rule: string, search: string
 * }} пустые строки и null там, где показать нечего; search — адрес поиска фото, если своего фото нет
 */
export function guideFor(row) {
  const name = String((row && row.machine) || '').trim();
  const exercise = clean(row && row.exercise);
  const machine = machineOf(name);

  let id = '';
  if (machine) id = ON_MACHINE[machine.id](exercise);
  else if (!name) id = (BY_NAME.find(([test]) => test.test(exercise)) || [])[1] || '';
  const move = Object.hasOwn(MOVES, id) ? MOVES[id] : null;
  const photo = machine && machine.photo ? { src: `${PHOTO_DIR}${machine.photo}.webp`, ...PHOTO_SIZE } : null;

  return {
    machine: name,
    photo,
    look: machine ? machine.look : '',
    art: move ? move.art : '',
    view: (move && move.view) || '',
    legend: move ? move.legend || LEGEND : '',
    muscles: move ? move.muscles : '',
    steps: move ? move.steps.slice() : [],
    rule: move && !move.cardio ? STRENGTH_RULE : '',
    // фото тренажёра в приложении нет: его можно поискать по названию. Дорожку искать незачем.
    search: name && !photo && !(move && move.cardio) ? `https://www.google.com/search?tbm=isch&q=${encodeURIComponent(name)}` : '',
  };
}

/** Все фотографии справочника: для проверки, что файлы на месте. */
export function guidePhotos() {
  return [...new Set(MACHINES.filter((item) => item.photo).map((item) => `${PHOTO_DIR}${item.photo}.webp`))];
}

/** Все рисунки, на которые ссылается справочник. */
export function guideArt() {
  return [...new Set(Object.values(MOVES).map((move) => move.art))];
}
